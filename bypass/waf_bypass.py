"""WAF detection and conservative payload variation helpers.

Use only during authorized security testing. These helpers are intended to
compare how defensive controls respond to equivalent test strings.
"""

from __future__ import annotations

import base64
import binascii
import random
import time
from dataclasses import dataclass
from typing import Iterable
from urllib.parse import quote

import requests


WAF_HEADER_SIGNATURES = {
    "cf-ray": "Cloudflare",
    "cf-cache-status": "Cloudflare",
    "server:cloudflare": "Cloudflare",
    "akamai-ghost": "Akamai",
    "x-akamai-transformed": "Akamai",
    "x-amzn-requestid": "AWS WAF",
    "x-amzn-trace-id": "AWS WAF",
    "incap_ses": "Imperva",
    "x-iinfo": "Imperva",
    "x-sucuri-id": "Sucuri",
    "x-sucuri-cache": "Sucuri",
    "mod_security": "ModSecurity",
}

WAF_BODY_SIGNATURES = {
    "attention required! | cloudflare": "Cloudflare",
    "cloudflare ray id": "Cloudflare",
    "access denied | akamai": "Akamai",
    "generated by cloudfront": "AWS WAF",
    "aws waf": "AWS WAF",
    "request unsuccessful. incapsula": "Imperva",
    "incident id": "Imperva",
    "mod_security": "ModSecurity",
    "sucuri website firewall": "Sucuri",
}

RATE_LIMIT_STATUSES = {429, 503}


@dataclass(frozen=True)
class WAFDetection:
    """A compact WAF detection result."""

    detected: bool
    name: str | None
    reason: str
    status_code: int | None = None
    rate_limited: bool = False


def _header_blob(headers: dict[str, str]) -> str:
    return "\n".join(f"{key.lower()}:{value.lower()}" for key, value in headers.items())


def detect_waf_from_response(response: requests.Response) -> WAFDetection:
    """Detect common WAF products from response headers and body text."""

    headers = _header_blob(dict(response.headers))
    body = response.text[:5000].lower()

    for signature, name in WAF_HEADER_SIGNATURES.items():
        if signature in headers:
            return WAFDetection(True, name, f"matched header signature: {signature}", response.status_code)

    for signature, name in WAF_BODY_SIGNATURES.items():
        if signature in body:
            return WAFDetection(True, name, f"matched body signature: {signature}", response.status_code)

    if response.status_code in {403, 406}:
        return WAFDetection(True, "Unknown WAF", f"blocking status code {response.status_code}", response.status_code)

    return WAFDetection(False, None, "no WAF signature matched", response.status_code)


def detect_waf(
    url: str,
    timeout: float = 5.0,
    headers: dict[str, str] | None = None,
    proxies: dict[str, str] | None = None,
    verify: bool | str = True,
) -> WAFDetection:
    """Request one URL and run WAF detection on the response."""

    try:
        response = requests.get(url, timeout=timeout, allow_redirects=False, headers=headers, proxies=proxies, verify=verify)
    except requests.RequestException as exc:
        return WAFDetection(False, None, f"request failed: {exc}", None)
    return detect_waf_from_response(response)


def case_switch(payload: str) -> str:
    """Alternate character case for alphabetic payload characters."""

    switched: list[str] = []
    upper = True
    for char in payload:
        if char.isalpha():
            switched.append(char.upper() if upper else char.lower())
            upper = not upper
        else:
            switched.append(char)
    return "".join(switched)


def unicode_escape(payload: str) -> str:
    """Represent visible ASCII characters with JavaScript-style unicode escapes."""

    return "".join(f"\\u{ord(char):04x}" if 32 <= ord(char) <= 126 else char for char in payload)


def whitespace_mutations(payload: str) -> list[str]:
    """Create whitespace-preserving payload variants."""

    return [
        payload.replace(" ", "\t"),
        payload.replace(" ", "\n"),
        payload.replace(" ", "/**/"),
    ]


def payload_encoding_rotation(payload: str) -> list[str]:
    """Return URL, double-URL, base64, and hex encodings."""

    url_encoded = quote(payload, safe="")
    return [
        url_encoded,
        quote(url_encoded, safe=""),
        base64.b64encode(payload.encode("utf-8")).decode("ascii"),
        binascii.hexlify(payload.encode("utf-8")).decode("ascii"),
    ]


def generate_bypass_payloads(payload: str) -> list[str]:
    """Return unique payload variants for authorized WAF behavior testing."""

    candidates = [
        payload,
        case_switch(payload),
        unicode_escape(payload),
        *whitespace_mutations(payload),
        *payload_encoding_rotation(payload),
    ]
    seen: set[str] = set()
    unique: list[str] = []
    for candidate in candidates:
        if candidate not in seen:
            seen.add(candidate)
            unique.append(candidate)
    return unique


def parameter_pollution_names(param: str) -> tuple[str, str]:
    """Return duplicate parameter names for HTTP parameter pollution tests."""

    return param, param


def method_rotation() -> tuple[str, ...]:
    """Return methods supported by the fuzzer for comparison checks."""

    return ("GET", "POST")


def is_rate_limited(response: requests.Response | None) -> bool:
    """Return True when a response indicates throttling."""

    if response is None:
        return False
    return response.status_code in RATE_LIMIT_STATUSES or "retry-after" in {key.lower() for key in response.headers}


def throttle_if_rate_limited(response: requests.Response | None, min_delay: float = 2.0, max_delay: float = 6.0) -> None:
    """Sleep briefly when a rate-limit response is observed."""

    if is_rate_limited(response):
        time.sleep(random.uniform(min_delay, max_delay))


def expand_payloads(payloads: Iterable[str]) -> list[str]:
    """Expand a payload collection with WAF variation candidates."""

    expanded: list[str] = []
    seen: set[str] = set()
    for payload in payloads:
        for candidate in generate_bypass_payloads(payload):
            if candidate in seen:
                continue
            seen.add(candidate)
            expanded.append(candidate)
    return expanded
